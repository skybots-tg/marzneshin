import { createContext, useContext } from "react";

/**
 * Режим «заголовок как подпись».
 *
 * На телефоне строка таблицы превращается в карточку, и каждому значению
 * нужна подпись — то же самое слово, что стоит в шапке колонки. Слово это
 * живёт внутри `header`, куда снаружи не заглянуть: там React-элемент, а не
 * строка, и у каждого модуля он свой.
 *
 * Поэтому вместо того чтобы дублировать подписи в описаниях колонок (а их
 * шесть десятков в десяти файлах, и они разъедутся при первой же правке),
 * шапка рендерится как есть, но в этом режиме отдаёт один текст без кнопки
 * сортировки и выпадающего меню.
 */
export const ColumnLabelModeContext = createContext(false);

export const useColumnLabelMode = () => useContext(ColumnLabelModeContext);
